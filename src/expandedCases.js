const hashText = (text) => [...text].reduce(
  (value, character) => ((value * 31) + character.charCodeAt(0)) >>> 0,
  2166136261,
);

const buildWrongOptions = (domain, diagnosis, correctLabel) => {
  const source = WRONG_BANKS[domain] ?? WRONG_BANKS.cardio;
  const offset = hashText(`${diagnosis}-${correctLabel}`) % source.length;
  const labels = [];
  for (let index = 0; labels.length < 4 && index < source.length * 2; index += 1) {
    const label = source[(offset + index) % source.length];
    if (label !== correctLabel && !labels.includes(label)) labels.push(label);
  }
  return labels.map((label, index) => ({
    l: label,
    t: [3, 5, 8, 10][index],
    ok: false,
    fb: `「${label}」は、この患者で優先する対応ではない。緊急度と病態を整理し直そう。`,
  }));
};

const buildStep = (domain, diagnosis, definition) => {
  const [q, answer, feedback, time = 5] = definition;
  return {
    q,
    opts: [
      { l: answer, t: time, ok: true, fb: feedback },
      ...buildWrongOptions(domain, diagnosis, answer),
    ],
  };
};

