const option = (l, t, ok, fb) => ({ l, t, ok, fb });
const step = (q, correct, correctFb, wrongs) => ({
  q,
  opts: [
    option(correct[0], correct[1], true, correctFb),
    ...wrongs.map(([l, t, fb]) => option(l, t, false, fb)),
  ],
});
const makeCase = (name, chief, dx, kokushi, diff, limit, steps) => ({
  name,
  chief,
  dx,
  kokushi,
  diff,
  limit,
  steps,
});

const simpleStep = (q, correct, correctFb, wrongs, correctTime = 5) =>
  step(
    q,
    [correct, correctTime],
    correctFb,
    wrongs.map((wrong, index) => {
      const [label, feedback] = Array.isArray(wrong) ? wrong : [wrong, null];
      const times = [3, 5, 8, 10];
      return [
        label,
        times[index] ?? 5,
        feedback ?? `「${label}」は、この状況で優先する対応ではない。病態と緊急度をもう一度整理しよう。`,
      ];
    }),
  );

const twoStepCase = (name, chief, dx, kokushi, diff, limit, first, second) =>
  makeCase(name, chief, dx, kokushi, diff, limit, [
    simpleStep(...first),
    simpleStep(...second),
  ]);

